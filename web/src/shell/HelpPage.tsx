import { Trans, useLingui } from "@lingui/react/macro";
import { AI_DISCLOSURE } from "../apps/chat/aiDisclosureText";
import { REPORT_REASONS } from "../apps/chat/report";
import { PaneSection } from "../apps/settings/PaneSection";
import { PageHeader } from "../patterns";
import { getAuthConfig } from "../lib/auth";
import { DEVELOPERS_PATH, PRICING_PATH } from "./frontDoor";
import { supportLinks } from "./frontDoorLinks";
import { ChordKeys } from "./ShortcutsHelp";
import { isMacPlatform, SHORTCUTS } from "./shortcuts";

/**
 * The help page: short, and only about what this app does that is not
 * obvious from its screen. Each section exists because a person could
 * reasonably ask "what happens if I…" and the answer is not on the button.
 *
 * Plain anchors throughout, like the legal pages: the page renders in a unit
 * test without a RouterProvider, and every target is a real path.
 *
 * The last section exists only when the deployment named a support URL or
 * a status page in /api/auth-config (Boot fetched it before this rendered);
 * without either there is nothing honest to link, so nothing is shown.
 *
 * The shortcut labels, the report reasons and the AI disclosure are the
 * chat app's own data and read as the chat app writes them; the prose
 * around them is this page's and is in the catalogue.
 */
export function HelpPage(props: { mac?: boolean }) {
  const { t } = useLingui();
  const mac = props.mac ?? isMacPlatform();
  const linkClass = "text-mw-link underline underline-offset-2 hover:text-mw-link-hover";
  const config = getAuthConfig();
  const support = supportLinks(config);
  return (
    <div className="h-full overflow-y-auto">
      <div className="mx-auto flex w-full max-w-3xl flex-col pb-10">
        <PageHeader
          title={t`Help`}
          description={t`What the chat does that is not written on its buttons: the shortcuts, what talking to an AI means here, and how to report, export and keep track of usage.`}
        />
        <div className="flex flex-col gap-4 px-4">
          <PaneSection title={t`Keyboard shortcuts`}>
            <dl className="flex flex-col gap-2">
              {SHORTCUTS.map((shortcut) => (
                <div key={shortcut.id} className="flex items-start justify-between gap-4">
                  <dt className="text-sm">
                    {shortcut.label}
                    {shortcut.hint && (
                      <span className="block text-xs text-mw-text-muted">{shortcut.hint}</span>
                    )}
                  </dt>
                  <dd className="flex shrink-0 items-center gap-1.5">
                    {shortcut.chords.map((chord, index) => (
                      <span key={index} className="contents">
                        {index > 0 && (
                          <span className="text-xs text-mw-text-muted">
                            <Trans>or</Trans>
                          </span>
                        )}
                        <ChordKeys chord={chord} mac={mac} />
                      </span>
                    ))}
                  </dd>
                </div>
              ))}
            </dl>
          </PaneSection>

          <PaneSection title={t`You are talking to an AI`}>
            <div className="flex flex-col gap-2 text-sm">
              <p className="font-medium">{AI_DISCLOSURE}</p>
              <p className="text-mw-text-muted">
                <Trans>
                  Every reply is generated by a language model, and the model that wrote it is named
                  under the reply. A model can state things confidently that are wrong, invented or
                  out of date, and it has no memory beyond this conversation and the instructions in
                  force for it. Check anything that matters before you act on it. Nobody is reading
                  your messages as you send them; the Instructions control above the transcript
                  shows exactly what shapes the answers.
                </Trans>
              </p>
            </div>
          </PaneSection>

          <PaneSection title={t`Reporting a conversation or a reply`}>
            <div className="flex flex-col gap-2 text-sm text-mw-text-muted">
              <p>
                <Trans>
                  Open the conversation actions menu (the three dots beside the model picker) and
                  choose <span className="text-mw-text">Report conversation</span>, or use the{" "}
                  <span className="text-mw-text">Report</span> action under a reply to report just
                  that reply. You will be asked which kind of problem it is:
                </Trans>
              </p>
              <ul className="list-disc pl-5">
                {REPORT_REASONS.map((reason) => (
                  <li key={reason.kind}>
                    <span className="text-mw-text">{reason.label}</span> — {reason.description}
                  </li>
                ))}
              </ul>
              <p>
                <Trans>
                  A report is stored with the conversation and answered with a reference you can
                  quote to support. It does not change the conversation, suspend anyone or tell the
                  model anything. If a report could not be stored you are told so, because a report
                  that was never filed must not look like one that was.
                </Trans>
              </p>
            </div>
          </PaneSection>

          <PaneSection title={t`Exporting a conversation`}>
            <p className="text-sm text-mw-text-muted">
              <Trans>
                The same menu offers <span className="text-mw-text">Export as Markdown</span> and{" "}
                <span className="text-mw-text">Export as JSON</span>. Both are built in your browser
                from the conversation already on screen, so nothing is sent anywhere and it works
                offline. Markdown is the branch you are reading, one section per turn, with
                attachments and tool calls named rather than embedded. JSON carries the same
                messages as the API sent them, plus every other branch of the conversation. The
                file is named after the conversation’s title. Everything on your account at once is
                under{" "}
                <a href="/settings/data" className={linkClass}>
                  Settings › Data
                </a>
                .
              </Trans>
            </p>
          </PaneSection>

          <PaneSection title={t`Usage, plans and billing`}>
            <ul className="flex flex-col gap-1 text-sm text-mw-text-muted">
              <li>
                <Trans>
                  <a href="/settings/usage" className={linkClass}>
                    Settings › Usage
                  </a>{" "}
                  — the tokens used this period, when they reset, the cost by model, and the
                  day-by-day history.
                </Trans>
              </li>
              <li>
                <Trans>
                  <a href="/settings/billing" className={linkClass}>
                    Settings › Billing
                  </a>{" "}
                  — the plan your organisation is on, the card, and the invoices.
                </Trans>
              </li>
              <li>
                <Trans>
                  <a href={PRICING_PATH} className={linkClass}>
                    Plans
                  </a>{" "}
                  — what each plan includes and what it costs.
                </Trans>
              </li>
            </ul>
          </PaneSection>

          <PaneSection title={t`Using the API`}>
            <p className="text-sm text-mw-text-muted">
              <Trans>
                The same models are reachable from your own code: the API speaks the OpenAI
                chat-completions format, so any OpenAI client works with a MatterWave key from{" "}
                <a href="/settings/keys" className={linkClass}>
                  Settings › API keys
                </a>
                . The{" "}
                <a href={DEVELOPERS_PATH} className={linkClass}>
                  developer portal
                </a>{" "}
                has the quickstart, the reference and the SDKs.
              </Trans>
            </p>
          </PaneSection>

          {support.length > 0 && (
            <PaneSection title={t`Support and status`}>
              <ul className="flex flex-col gap-1 text-sm text-mw-text-muted">
                {config?.support_url && (
                  <li>
                    <Trans>
                      <a href={config.support_url} className={linkClass} target="_blank" rel="noopener noreferrer">
                        Contact support
                      </a>{" "}
                      — quote the request id shown with an error, and never paste an API key.
                    </Trans>
                  </li>
                )}
                {config?.status_url && (
                  <li>
                    <Trans>
                      <a href={config.status_url} className={linkClass} target="_blank" rel="noopener noreferrer">
                        Service status
                      </a>{" "}
                      — whether MatterWave is up, and any incident in progress.
                    </Trans>
                  </li>
                )}
              </ul>
            </PaneSection>
          )}
        </div>
      </div>
    </div>
  );
}
